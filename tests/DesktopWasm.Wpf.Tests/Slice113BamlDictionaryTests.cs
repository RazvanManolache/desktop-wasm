    private static byte[] DictionaryDoc((string Key, string Text, uint Offset) first,
        (string Key, string Text, uint Offset) second)
    {
        // Root RD + StringInfo keys + key-position index + two scalar Color
        // entries; the caller passes the honest content offsets.
        var b = new B().Raw(Header()).Raw(0x01);
        b.Raw(0x03).I16(-524).Raw(0x00);
        var keys = new[] { first.Key, second.Key }.Distinct().ToList();
        foreach (var (id, key) in keys.Select((k, i) => (i, k)))
            b.Sized(0x20, p => p.U16((ushort)id).Str(key));
        int Id(string k) => keys.IndexOf(k);
        var deferPos = b.Position;
        b.Raw(0x25).U32(0); // patched below to land on the RD ElementEnd
        b.Sized(0x26, p => p.U16((ushort)Id(first.Key)).U32(first.Offset).U16(0));
        b.Sized(0x26, p => p.U16((ushort)Id(second.Key)).U32(second.Offset).U16(0));
        b.Raw(0x03).I16(-81).Raw(0x01);
        b.Sized(0x11, p => p.Str(first.Text).I16(-87));
        b.Raw(0x04);
        b.Raw(0x03).I16(-81).Raw(0x01);
        b.Sized(0x11, p => p.Str(second.Text).I16(-87));
        b.Raw(0x04);
        var endPos = b.Position;
        b.Raw(0x04, 0x02);
        // The skip lands on the dictionary's closing ElementEnd.
        var skip = (uint)(endPos - (deferPos + 5));
        var bytes = b.ToArray();
        bytes[deferPos + 1] = (byte)(skip & 0xFF);
        bytes[deferPos + 2] = (byte)((skip >> 8) & 0xFF);
        bytes[deferPos + 3] = (byte)((skip >> 16) & 0xFF);
        bytes[deferPos + 4] = (byte)((skip >> 24) & 0xFF);
        return bytes;
    }

    private sealed class B
    {
        private readonly List<byte> _b = new();
        public int Position => _b.Count;
        public B Raw(params byte[] b) { _b.AddRange(b); return this; }
        public B U16(ushort v) { _b.AddRange(BitConverter.GetBytes(v)); return this; }
        public B I16(short v) { _b.AddRange(BitConverter.GetBytes(v)); return this; }
        public B U32(uint v) { _b.AddRange(BitConverter.GetBytes(v)); return this; }
        public B Str(string s)
        {
            var ascii = Encoding.ASCII.GetBytes(s);
            Seven(ascii.Length);
            _b.AddRange(ascii);
            return this;
        }
        public B Seven(int v)
        {
            uint u = (uint)v;
            while (u >= 0x80) { _b.Add((byte)(u | 0x80)); u >>= 7; }
            _b.Add((byte)u);
            return this;
        }
        public B Sized(byte type, Action<B> payload)
        {
            var inner = new B();
            payload(inner);
            var p = inner._b;
            if (p.Count + 1 >= 128) throw new InvalidOperationException("test record too large");
            _b.Add(type);
            _b.Add((byte)(p.Count + 1));
            _b.AddRange(p);
            return this;
        }
        public byte[] ToArray() => _b.ToArray();
    }

