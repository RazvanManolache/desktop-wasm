        Assert.Equal(2447, colors.Length);
        var dictionary = BamlReader.LoadDictionary(colors);
        Assert.Null(dictionary.Source);
        Assert.Equal(35, dictionary.Keys.Cast<object>().Count());
        Assert.Equal(Color.FromArgb(0xFF, 0xF3, 0xFB, 0xFF),
            Assert.IsType<Color>(dictionary["LightPrimaryColor"]));
